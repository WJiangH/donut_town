// Modern Chem Pod v4: explicit furniture islands measured against the final art.
// Bake with: node scripts/build-chempod-walkmask.mjs
import { writeFileSync } from 'node:fs';
const cols = 224, rows = 126;
// These coordinates describe sprite FEET. Furniture overhangs are rendered in
// front of people behind them; color segmentation would mistake wood for floor.
const geometry = {
  floor: [
    { left: 12, right: 89, top: 41, bottom: 77 },
    { left: 28, right: 72, top: 77, bottom: 80 },
    { left: 43, right: 56, top: 77, bottom: 92 }
  ],
  blocked: [
    { left: 21.5, right: 42, top: 48, bottom: 69.5, note: 'west experiment bench' },
    { left: 57.5, right: 78, top: 48, bottom: 69.5, note: 'east experiment bench' },
    { left: 6, right: 16, top: 48, bottom: 73, note: 'reading console and plant' },
    { left: 83, right: 95, top: 48, bottom: 73, note: 'coffee console and plant' }
  ]
};
const contains = (r, x, y) => x >= r.left && x <= r.right && y >= r.top && y <= r.bottom;
const open = new Uint8Array(cols * rows);
for (let row = 0; row < rows; row++) for (let col = 0; col < cols; col++) {
  const x = (col + .5) / cols * 100, y = (row + .5) / rows * 100;
  open[row * cols + col] = geometry.floor.some(r => contains(r, x, y)) && !geometry.blocked.some(r => contains(r, x, y)) ? 1 : 0;
}
// Refuse disconnected floor instead of silently accepting unreachable stations.
const start = Math.floor(.86 * rows) * cols + Math.floor(.5 * cols);
const seen = new Set([start]), queue = [start];
if (!open[start]) throw new Error('Chem Pod doorway is blocked');
while (queue.length) {
  const i = queue.pop(), x = i % cols, y = Math.floor(i / cols);
  for (const [dx, dy] of [[1,0],[-1,0],[0,1],[0,-1]]) {
    const nx = x + dx, ny = y + dy, next = ny * cols + nx;
    if (nx < 0 || nx >= cols || ny < 0 || ny >= rows || !open[next] || seen.has(next)) continue;
    seen.add(next); queue.push(next);
  }
}
const count = open.reduce((n, v) => n + v, 0);
if (seen.size !== count) throw new Error('Chem Pod floor has disconnected regions');
const bytes = Buffer.alloc(Math.ceil(open.length / 8));
for (let i = 0; i < open.length; i++) if (open[i]) bytes[i >> 3] |= 1 << (i & 7);
writeFileSync(new URL('../assets/chempod-walkmask.js', import.meta.url), `// Generated by scripts/build-chempod-walkmask.mjs - do not edit by hand.
window.CHEMPOD_WALK_MASK = ${JSON.stringify({ cols, rows, geometry, bits: bytes.toString('base64') }, null, 2)};
`);
console.log(`Chem Pod v4: ${cols}x${rows}, ${count} connected floor cells`);
